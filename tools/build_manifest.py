"""Compile the critical JSON inventory and trust anchor. No signing secret is used."""
import argparse,hashlib,json
from pathlib import Path

def products(root):
    manifest=root/'data/critical-manifest.json'
    paths=sorted({*[(p.relative_to(root).as_posix()) for p in (root/'data').rglob('*.json') if p!=manifest],'assets/audio/catalog.json'})
    raw={('res://'+p):(root/p).read_bytes() for p in paths}
    snapshot={p:json.loads(text) for p,text in raw.items()}
    encoded=(json.dumps({'version':1,'files':{p:hashlib.sha256(text).hexdigest() for p,text in raw.items()}},ensure_ascii=True,sort_keys=True,indent=2)+'\n').encode()
    literal=json.dumps(json.dumps(snapshot,ensure_ascii=True,sort_keys=True,separators=(',',':')),ensure_ascii=True)
    source=('# Generated by tools/build_manifest.py; edit the original JSON, then regenerate.\n'
        'extends RefCounted\nconst MANIFEST_SHA256: String = '+json.dumps(hashlib.sha256(encoded).hexdigest())+'\n'
        'const JSON_TEXT: String = '+literal+'\n').encode()
    return {manifest:encoded,root/'scripts/security/TrustedData.gd':source}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    root=Path(__file__).resolve().parents[1]
    stale=[]
    for path,content in products(root).items():
        if args.check:
            if not path.is_file() or path.read_bytes()!=content:stale.append(path.relative_to(root).as_posix())
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(content)
    if stale:raise SystemExit('Critical-data trust anchor is stale: '+', '.join(stale))
    print('CRITICAL DATA TRUST ANCHOR '+('VERIFIED' if args.check else 'GENERATED'))
if __name__=='__main__':main()
